    [Fact]
    public void GetContent_SameFields_ReturnsTheSameText()
    {
        var same = new Zapper.Domain.Payment.AcmePaymentAdvice(
            Base.RequestType,
            Base.MerchantId,
            Base.TransactionId,
            Base.AcmeTransactionAt,
            Base.OrderNumber,
            Base.ReconciliationId,
            Base.RetrievalReferenceNumber,
            Base.SystemsTraceAuditNumber,
            Base.Amount,
            Base.CurrencyCode,
            Base.PaymentService,
            Base.TransactionStatus,
            Base.ResponseSource,
            Base.ResponseCode,
            Base.ResponseDescription,
            Base.AuthorisationCode,
            Base.CommunicationProtocol);

        var content = same.GetContent();

        content.ShouldBe(Base.GetContent());
    }

    [Theory]
    [MemberData(nameof(ChangedFields))]
    public void GetContent_OneMappedFieldChanged_ReturnsOtherText(string field, Zapper.Domain.Payment.AcmePaymentAdvice changed)
    {
        var content = changed.GetContent();

        content.ShouldNotBe(Base.GetContent(), field);
    }
